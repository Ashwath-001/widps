import { WifiOff, FlaskConical } from 'lucide-react';
import { useBackendHealth } from '../../lib/health';
import { useSystemStatus } from '../../hooks/useMockLiveData';

/** Shown when the sensor stops answering (data on screen is stale) or runs on simulated data. */
export default function ConnectionBanner() {
  const { online, lastOk } = useBackendHealth();
  const status = useSystemStatus();
  if (!online) {
    const since = lastOk ? `Showing data from ${new Date(lastOk).toLocaleTimeString('en-GB')}.` : 'No data received yet.';
    return (
      <div role="alert" className="mb-4 flex items-center gap-2 rounded-lg border border-red-500/30 bg-red-500/10 px-3 py-2 text-xs text-red-300">
        <WifiOff size={14} className="shrink-0" />
        <span><strong>Sensor unreachable.</strong> {since} Values below may be out of date.</span>
      </div>
    );
  }
  if (status.captureMode === 'simulated') {
    return (
      <div role="status" className="mb-4 flex items-center gap-2 rounded-lg border border-yellow-500/30 bg-yellow-500/10 px-3 py-2 text-xs text-yellow-300">
        <FlaskConical size={14} className="shrink-0" />
        <span><strong>Simulated data.</strong> The monitor interface is not available, so alerts and networks are generated by the simulator.</span>
      </div>
    );
  }
  return null;
}
